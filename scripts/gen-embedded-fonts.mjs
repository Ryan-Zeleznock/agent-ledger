// Regenerate with: node scripts/gen-embedded-fonts.mjs (no network or build-time asset copying).
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../src/report/', import.meta.url);
const faces = [
  ['Source Serif 4', '400 600', 'SourceSerif4-variable-latin.woff2'],
  ['IBM Plex Sans Condensed', '400', 'IBMPlexSansCondensed-400-latin.woff2'],
  ['IBM Plex Sans Condensed', '600', 'IBMPlexSansCondensed-600-latin.woff2'],
  ['JetBrains Mono', '400', 'JetBrainsMono-400-latin.woff2'],
];
const css = [];
for (const [family, weight, file] of faces) {
  const bytes = await readFile(new URL(`fonts/${file}`, root));
  css.push(`@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${bytes.toString('base64')}) format("woff2")}`);
}
const notices = [];
for (const file of ['OFL-SourceSerif4.txt', 'OFL-IBMPlex.txt', 'OFL-JetBrainsMono.txt']) {
  notices.push(await readFile(new URL(`fonts/${file}`, root), 'utf8'));
}
const output = '// Generated by scripts/gen-embedded-fonts.mjs; do not edit. Font licenses: src/report/fonts/OFL-*.txt.\n'
  + `export const embeddedFontCss = ${JSON.stringify(css.join('\n'))};\n`
  + `export const fontLicenseNotices = ${JSON.stringify(notices)};\n`;
const target = new URL('embedded-fonts.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Embedded fonts are stale; regenerate them.');
} else await writeFile(target, output);
